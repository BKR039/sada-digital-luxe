import { createClient } from "@supabase/supabase-js";
import fs from "fs";
import {
  createDeal,
  updateDeal,
  updateLeadStage,
  convertLeadToSale,
  fetchDeals,
  fetchSalesCommissions,
  approveCommission,
  payoutCommission,
  deleteDeal,
  calculateDealCommission,
} from "../src/lib/sales-service";

const envContent = fs.readFileSync(".env", "utf-8");
const env: Record<string, string> = {};
envContent.split(/\r?\n/).forEach((line) => {
  const match = line.match(/^\s*([\w.-]+)\s*=\s*(.*)?\s*$/);
  if (match) {
    let value = (match[2] || "").trim();
    if (value.startsWith('"') && value.endsWith('"')) {
      value = value.substring(1, value.length - 1);
    }
    env[match[1]] = value;
    process.env[match[1]] = value;
  }
});
Object.assign(process.env, env);

const client = createClient(env.VITE_SUPABASE_URL, env.VITE_SUPABASE_PUBLISHABLE_KEY);

interface TestResults {
  name: string;
  passed: boolean;
  details?: string;
  error?: string;
}

const results: TestResults[] = [];

async function main() {
  console.log("============================================================");
  console.log("SADA OS — SALES PIPELINE & COMMISSION PRODUCTION TEST SUITE");
  console.log("============================================================\n");

  // Step 0: Authenticate as Super Admin
  const authRes = await client.auth.signInWithPassword({
    email: "qa.superadmin@sada.agency",
    password: "SuperAdminPassword123!",
  });
  if (authRes.error) {
    console.error("Super Admin authentication failed:", authRes.error);
    process.exit(1);
  }
  const superAdminId = authRes.data.user.id;
  const superAdminCtx = { role: "super_admin" as const, userId: superAdminId };

  // Fetch a package from package_catalog
  const { data: pkgs } = await client
    .from("package_catalog")
    .select("id, name, price")
    .eq("is_active", true)
    .limit(1);
  const samplePkg = pkgs?.[0];

  // Fetch a client
  const { data: clients } = await client.from("clients").select("id, name").limit(1);
  const sampleClient = clients?.[0];

  // Fetch target worker BKR039
  const targetWorkerId = "560fd7c4-c38b-4562-8f9d-95729dfb2bab";
  const { data: workerTm } = await client
    .from("team_members")
    .select("id, name, profile_id")
    .eq("profile_id", targetWorkerId)
    .maybeSingle();

  console.log("Environment initialized:");
  console.log(`- Super Admin: ${superAdminId}`);
  console.log(`- Sample Package: ${samplePkg?.name} (${samplePkg?.id})`);
  console.log(`- Sample Client: ${sampleClient?.name} (${sampleClient?.id})`);
  console.log(`- Target Worker Member: ${workerTm?.name} (${workerTm?.id})\n`);

  let testDealId: string | null = null;
  let testCommId: string | null = null;

  try {
    // ----------------------------------------------------
    // TEST 1: Lead Creation & Validation
    // ----------------------------------------------------
    console.log("TEST 1: Creating QA Lead with explicit sales assignment...");
    const timestamp = Date.now();
    const dealTitle = `QA Production Suite Deal ${timestamp}`;
    const companyName = `QA Automated Suites SARL ${timestamp}`;

    const createdDeal = await createDeal({
      title: dealTitle,
      companyName: companyName,
      contactName: "Sami Ben Amor",
      contactEmail: "sami@qa-suites.tn",
      contactPhone: "+216 22 123 456",
      packageId: samplePkg?.id,
      stage: "lead",
      salesOwnerId: targetWorkerId,
      commissionRecipientId: workerTm?.id,
      dealValue: 3500,
      serviceRevenue: 2500,
      sponsoringBudget: 1000,
      commissionRate: 15,
      expectedCloseDate: "2026-11-15",
      notes: "Lead generated by automated production test suite.",
      ctx: superAdminCtx,
      actorRole: "super_admin",
      client: client,
    });

    if (createdDeal && createdDeal.id) {
      testDealId = createdDeal.id;
      const pass =
        createdDeal.title === dealTitle &&
        createdDeal.stage === "lead" &&
        Number(createdDeal.deal_value) === 3500 &&
        Number(createdDeal.service_revenue) === 2500 &&
        Number(createdDeal.sponsoring_budget) === 1000 &&
        createdDeal.sales_owner_id === targetWorkerId;

      results.push({
        name: "1. Lead Creation & Attribution",
        passed: pass,
        details: `Deal ID: ${testDealId}, Owner: ${createdDeal.sales_owner_id}`,
      });
      console.log("   -> PASS: Created deal successfully.\n");
    } else {
      results.push({
        name: "1. Lead Creation & Attribution",
        passed: false,
        error: "Created deal returned null or missing ID",
      });
    }

    // ----------------------------------------------------
    // TEST 2: Deal Editing & Financial Parameters Persistence
    // ----------------------------------------------------
    console.log("TEST 2: Updating deal parameters and verifying persistence...");
    const updatedDeal = await updateDeal(
      testDealId!,
      {
        title: `${dealTitle} [Amended Scope]`,
        dealValue: 4000,
        serviceRevenue: 3000,
        sponsoringBudget: 1000,
        notes: "Scope amended to include advanced reels delivery.",
      },
      {
        ctx: superAdminCtx,
        actorRole: "super_admin",
        actorId: superAdminId,
        client: client,
      }
    );

    const editPass =
      updatedDeal.title.includes("[Amended Scope]") &&
      Number(updatedDeal.deal_value) === 4000 &&
      Number(updatedDeal.service_revenue) === 3000;

    results.push({
      name: "2. Deal Editing & Persistence",
      passed: editPass,
      details: `Title: ${updatedDeal.title}, Value: ${updatedDeal.deal_value} TND`,
    });
    console.log(`   -> ${editPass ? "PASS" : "FAIL"}: Deal edited.\n`);

    // ----------------------------------------------------
    // TEST 3: Pipeline Stage Transitions
    // ----------------------------------------------------
    console.log("TEST 3: Testing sequential pipeline stage transitions...");
    const stagesToTest: Array<"contacted" | "qualified" | "meeting" | "proposal" | "negotiation"> = [
      "contacted",
      "qualified",
      "meeting",
      "proposal",
      "negotiation",
    ];

    let currentStage = "lead";
    let allStagesPassed = true;

    for (const nextStage of stagesToTest) {
      const stageRes = await updateLeadStage({
        leadId: testDealId!,
        fromStage: currentStage,
        newStage: nextStage,
        actorCtx: superAdminCtx,
        actorRole: "super_admin",
        actorId: superAdminId,
        client: client,
      });

      if (!stageRes.success) {
        allStagesPassed = false;
        console.error(`   Failed transition from ${currentStage} to ${nextStage}:`, stageRes.error);
        break;
      }
      currentStage = nextStage;
    }

    results.push({
      name: "3. Pipeline Stage Transitions (lead -> negotiation)",
      passed: allStagesPassed,
      details: `Final stage reached: ${currentStage}`,
    });
    console.log(`   -> ${allStagesPassed ? "PASS" : "FAIL"}: Stages advanced to negotiation.\n`);

    // ----------------------------------------------------
    // TEST 4: Convert to Won Sale (convertLeadToSale) & Sponsoring Exclusion Formula
    // ----------------------------------------------------
    console.log("TEST 4: Converting lead to won sale with sponsoring deduction...");
    // Commercial numbers: Sale Amount = 4,000 TND, Sponsoring = 1,000 TND
    // Expected Commissionable Base = 4,000 - 1,000 = 3,000 TND
    // Expected Commission @ 15% = 3,000 * 15 / 100 = 450 TND
    const convertRes = await convertLeadToSale({
      dealId: testDealId!,
      clientId: sampleClient?.id,
      packageId: samplePkg?.id,
      saleAmount: 4000,
      sponsoringAmount: 1000,
      paymentStatus: "unpaid",
      saleDate: "2026-10-11",
      notes: "Commercial contract signed and awaiting commission approval.",
      ctx: superAdminCtx,
      actorRole: "super_admin",
      actorId: superAdminId,
      client: client,
    });

    if (!convertRes.success) {
      results.push({
        name: "4. Convert to Won Sale RPC",
        passed: false,
        error: convertRes.error,
      });
      console.error("   -> FAIL: Convert lead failed:", convertRes.error);
    } else {
      // Verify deal in DB
      const { data: dbDeal } = await client.from("deals").select("*").eq("id", testDealId).single();
      const { data: dbComms } = await client.from("sales_commissions").select("*").eq("deal_id", testDealId);

      const comm = dbComms?.[0];
      testCommId = comm?.id || null;

      const conversionPass =
        dbDeal.stage === "won" &&
        Number(dbDeal.deal_value) === 4000 &&
        Number(dbDeal.service_revenue) === 3000 &&
        Number(dbDeal.sponsoring_budget) === 1000 &&
        dbDeal.commission_rule_snapshot !== null &&
        dbComms?.length === 1 &&
        Number(comm.total_sale_amount) === 4000 &&
        Number(comm.service_revenue) === 3000 &&
        Number(comm.sponsoring_amount) === 1000 &&
        Number(comm.commission_rate) === 15 &&
        Number(comm.commission_amount) === 450;

      results.push({
        name: "4. Convert to Won Sale & Sponsoring Exclusion Formula",
        passed: conversionPass,
        details: `Deal Stage: ${dbDeal.stage}, Comm: ${comm?.commission_amount} TND (Rate: ${comm?.commission_rate}%, Base: ${comm?.service_revenue} TND)`,
      });
      console.log(`   -> ${conversionPass ? "PASS" : "FAIL"}: Conversion formula verified.\n`);
    }

    // ----------------------------------------------------
    // TEST 5: Conversion Idempotency & Repeated Submissions
    // ----------------------------------------------------
    console.log("TEST 5: Testing conversion idempotency (repeated submission)...");
    const retryRes = await convertLeadToSale({
      dealId: testDealId!,
      clientId: sampleClient?.id,
      packageId: samplePkg?.id,
      saleAmount: 4000,
      sponsoringAmount: 1000,
      paymentStatus: "unpaid",
      notes: "Retry submission should not duplicate commission.",
      ctx: superAdminCtx,
      actorRole: "super_admin",
      actorId: superAdminId,
      client: client,
    });

    const { data: retryComms } = await client.from("sales_commissions").select("*").eq("deal_id", testDealId);
    const idempotencyPass = retryRes.success && retryComms?.length === 1;

    results.push({
      name: "5. Conversion Idempotency (No Duplicate Commission)",
      passed: idempotencyPass,
      details: `Commission records count: ${retryComms?.length}`,
    });
    console.log(`   -> ${idempotencyPass ? "PASS" : "FAIL"}: Idempotency verified.\n`);

    // ----------------------------------------------------
    // TEST 6: Commission Approval & Payout Lifecycle
    // ----------------------------------------------------
    if (testCommId) {
      console.log("TEST 6: Testing Commission Approval and Payout workflow...");
      // A. Test Worker approval restriction with authentic worker session
      const workerClient = createClient(env.VITE_SUPABASE_URL, env.VITE_SUPABASE_PUBLISHABLE_KEY);
      const workerAuth = await workerClient.auth.signInWithPassword({
        email: "qa.worker@sada.agency",
        password: "WorkerPassword123!",
      });
      const qaWorkerUserId = workerAuth.data.user!.id;
      const workerCtx = { role: "worker" as const, userId: qaWorkerUserId };
      const workerApproveRes = await approveCommission(testCommId, {
        ctx: workerCtx,
        actorRole: "worker",
        actorId: qaWorkerUserId,
        client: workerClient,
      });

      const workerBlockedPass = !workerApproveRes.success && (
        workerApproveRes.error?.includes("FORBIDDEN_ADMIN_ACTION") ||
        workerApproveRes.error?.includes("Workers cannot approve sales commissions") ||
        workerApproveRes.error?.includes("Unauthorized") ||
        workerApproveRes.error?.includes("disabled for this account")
      );
      console.log(`   Worker approval blocked as expected: ${workerBlockedPass} (${workerApproveRes.error})`);

      // B. Super Admin approves commission
      const adminApproveRes = await approveCommission(testCommId, {
        ctx: superAdminCtx,
        actorRole: "super_admin",
        actorId: superAdminId,
        client: client,
      });

      const { data: approvedComm } = await client
        .from("sales_commissions")
        .select("status, approved_by, approved_at")
        .eq("id", testCommId)
        .single();

      const approvalPass =
        adminApproveRes.success &&
        approvedComm.status === "approved" &&
        approvedComm.approved_by === superAdminId &&
        approvedComm.approved_at !== null;

      results.push({
        name: "6. Commission Approval (Worker Guard & Admin Persistence)",
        passed: workerBlockedPass && approvalPass,
        details: `Status: ${approvedComm.status}, ApprovedBy: ${approvedComm.approved_by}`,
      });
      console.log(`   -> ${approvalPass ? "PASS" : "FAIL"}: Commission approved with actor and timestamp.\n`);

      // C. Payout commission
      console.log("TEST 7: Testing Commission Payout...");
      const payoutRes = await payoutCommission(testCommId, {
        ctx: superAdminCtx,
        actorRole: "super_admin",
        actorId: superAdminId,
        client: client,
      });

      const { data: paidComm } = await client
        .from("sales_commissions")
        .select("status, updated_at")
        .eq("id", testCommId)
        .single();

      const payoutPass = payoutRes.success && paidComm.status === "paid";

      // Test repeated payout idempotency
      const repeatPayoutRes = await payoutCommission(testCommId, {
        ctx: superAdminCtx,
        actorRole: "super_admin",
        actorId: superAdminId,
        client: client,
      });
      const repeatPass = repeatPayoutRes.success;

      results.push({
        name: "7. Commission Payout & Disbursed Lifecycle",
        passed: payoutPass && repeatPass,
        details: `Final Status: ${paidComm.status}`,
      });
      console.log(`   -> ${payoutPass && repeatPass ? "PASS" : "FAIL"}: Commission marked paid.\n`);
    }

    // ----------------------------------------------------
    // TEST 8: fetchSalesCommissions Relation Joins
    // ----------------------------------------------------
    console.log("TEST 8: Testing fetchSalesCommissions relation joins (deal, client, team_member)...");
    const commsList = await fetchSalesCommissions({ ctx: superAdminCtx, client: client });
    const targetCommRow = commsList.find((c) => c.id === testCommId);

    const joinsPass =
      targetCommRow !== undefined &&
      targetCommRow.client?.name !== undefined &&
      targetCommRow.deal?.title !== undefined &&
      targetCommRow.team_member?.name !== undefined;

    results.push({
      name: "8. Commission Query Relation Joins",
      passed: joinsPass,
      details: `Client: ${targetCommRow?.client?.name}, Deal: ${targetCommRow?.deal?.title}, Rep: ${targetCommRow?.team_member?.name}`,
    });
    console.log(`   -> ${joinsPass ? "PASS" : "FAIL"}: Full relation joins verified.\n`);

  } finally {
    // ----------------------------------------------------
    // CLEANUP DISPOSABLE QA TEST RECORD
    // ----------------------------------------------------
    console.log("CLEANUP: Cleaning up disposable QA test fixtures...");
    if (testCommId) {
      await client.from("sales_commissions").delete().eq("id", testCommId);
      console.log(`   Cleaned commission fixture: ${testCommId}`);
    }
    if (testDealId) {
      await deleteDeal(testDealId, { ctx: superAdminCtx, actorRole: "super_admin", actorId: superAdminId, client: client });
      console.log(`   Cleaned deal fixture: ${testDealId}`);
    }
  }

  // ----------------------------------------------------
  // TEST REPORT
  // ----------------------------------------------------
  console.log("\n============================================================");
  console.log("TEST SUITE EXECUTION SUMMARY");
  console.log("============================================================");
  console.table(
    results.map((r) => ({
      Test: r.name,
      Status: r.passed ? "PASSED" : "FAILED",
      Details: r.details || r.error || "N/A",
    }))
  );

  const passedCount = results.filter((r) => r.passed).length;
  const failedCount = results.filter((r) => !r.passed).length;
  console.log(`\nTotal: ${results.length} | Passed: ${passedCount} | Failed: ${failedCount}`);

  if (failedCount > 0) {
    process.exit(1);
  }
}

main().catch((err) => {
  console.error("Unhandled error in test suite:", err);
  process.exit(1);
});
